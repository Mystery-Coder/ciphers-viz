const RCON = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36];

const normalizeHex = (input: string): string =>
	input.trim().replace(/^0x/i, "").replace(/\s+/g, "");

const parseHex = (
	input: string,
	expectedBytes: number,
): { bytes: number[]; error?: string } => {
	const cleaned = normalizeHex(input);
	if (cleaned.length !== expectedBytes * 2) {
		return {
			bytes: [],
			error: `Expected ${expectedBytes * 2} hex chars (${expectedBytes} bytes).`,
		};
	}
	if (!/^[0-9a-fA-F]+$/.test(cleaned)) {
		return { bytes: [], error: "Hex input must use 0-9 and A-F." };
	}
	const bytes = [] as number[];
	for (let i = 0; i < cleaned.length; i += 2) {
		bytes.push(Number.parseInt(cleaned.slice(i, i + 2), 16) & 0xff);
	}
	return { bytes };
};

const bytesToHex = (bytes: number[]): string =>
	bytes
		.map((byte) => byte.toString(16).padStart(2, "0"))
		.join("")
		.toUpperCase();

const xorWord = (a: number[], b: number[]): number[] =>
	a.map((value, i) => (value ^ b[i]) & 0xff);

const rotWord = (word: number[]): number[] => [
	word[1],
	word[2],
	word[3],
	word[0],
];

const subWord = (word: number[]): number[] => word.map((b) => SBOX[b]);

const expandKey = (key: number[]): number[][] => {
	const Nk = 4;
	const Nb = 4;
	const Nr = 10;
	const w: number[][] = [];

	for (let i = 0; i < Nk; i += 1) {
		w.push(key.slice(i * 4, i * 4 + 4));
	}

	for (let i = Nk; i < Nb * (Nr + 1); i += 1) {
		let temp = w[i - 1].slice();
		if (i % Nk === 0) {
			temp = subWord(rotWord(temp));
			temp[0] ^= RCON[i / Nk - 1];
		}
		w.push(xorWord(w[i - Nk], temp));
	}

	const roundKeys: number[][] = [];
	for (let r = 0; r <= Nr; r += 1) {
		const roundKey: number[] = [];
		for (let c = 0; c < Nb; c += 1) {
			roundKey.push(...w[r * Nb + c]);
		}
		roundKeys.push(roundKey);
	}
	return roundKeys;
};

const addRoundKey = (state: number[], roundKey: number[]): number[] =>
	state.map((value, i) => (value ^ roundKey[i]) & 0xff);

const subBytes = (state: number[]): number[] => state.map((b) => SBOX[b]);
const invSubBytes = (state: number[]): number[] =>
	state.map((b) => INV_SBOX[b]);

const shiftRows = (state: number[]): number[] => {
	const shifted = new Array(16).fill(0);
	for (let row = 0; row < 4; row += 1) {
		for (let col = 0; col < 4; col += 1) {
			const srcCol = (col + row) % 4;
			shifted[row + 4 * col] = state[row + 4 * srcCol];
		}
	}
	return shifted;
};

const invShiftRows = (state: number[]): number[] => {
	const shifted = new Array(16).fill(0);
	for (let row = 0; row < 4; row += 1) {
		for (let col = 0; col < 4; col += 1) {
			const srcCol = (col - row + 4) % 4;
			shifted[row + 4 * col] = state[row + 4 * srcCol];
		}
	}
	return shifted;
};

const gmul = (a: number, b: number): number => {
	let p = 0;
	let x = a;
	let y = b;
	for (let i = 0; i < 8; i += 1) {
		if (y & 1) {
			p ^= x;
		}
		const hiBit = x & 0x80;
		x = (x << 1) & 0xff;
		if (hiBit) {
			x ^= 0x1b;
		}
		y >>= 1;
	}
	return p & 0xff;
};

const mixColumns = (state: number[]): number[] => {
	const mixed = state.slice();
	for (let col = 0; col < 4; col += 1) {
		const i = col * 4;
		const s0 = state[i];
		const s1 = state[i + 1];
		const s2 = state[i + 2];
		const s3 = state[i + 3];
		mixed[i] = gmul(s0, 2) ^ gmul(s1, 3) ^ s2 ^ s3;
		mixed[i + 1] = s0 ^ gmul(s1, 2) ^ gmul(s2, 3) ^ s3;
		mixed[i + 2] = s0 ^ s1 ^ gmul(s2, 2) ^ gmul(s3, 3);
		mixed[i + 3] = gmul(s0, 3) ^ s1 ^ s2 ^ gmul(s3, 2);
	}
	return mixed.map((b) => b & 0xff);
};

const invMixColumns = (state: number[]): number[] => {
	const mixed = state.slice();
	for (let col = 0; col < 4; col += 1) {
		const i = col * 4;
		const s0 = state[i];
		const s1 = state[i + 1];
		const s2 = state[i + 2];
		const s3 = state[i + 3];
		mixed[i] = gmul(s0, 14) ^ gmul(s1, 11) ^ gmul(s2, 13) ^ gmul(s3, 9);
		mixed[i + 1] = gmul(s0, 9) ^ gmul(s1, 14) ^ gmul(s2, 11) ^ gmul(s3, 13);
		mixed[i + 2] = gmul(s0, 13) ^ gmul(s1, 9) ^ gmul(s2, 14) ^ gmul(s3, 11);
		mixed[i + 3] = gmul(s0, 11) ^ gmul(s1, 13) ^ gmul(s2, 9) ^ gmul(s3, 14);
	}
	return mixed.map((b) => b & 0xff);
};

const encryptBlock = (block: number[], roundKeys: number[][]): AesRound[] => {
	const rounds: AesRound[] = [];
	let state = addRoundKey(block, roundKeys[0]);
	rounds.push({
		step: 0,
		keyIndex: 0,
		label: "Round 0 (AddRoundKey)",
		state: state.slice(),
		roundKey: roundKeys[0].slice(),
	});

	for (let round = 1; round < 10; round += 1) {
		state = subBytes(state);
		state = shiftRows(state);
		state = mixColumns(state);
		state = addRoundKey(state, roundKeys[round]);
		rounds.push({
			step: round,
			keyIndex: round,
			label: `Round ${round}`,
			state: state.slice(),
			roundKey: roundKeys[round].slice(),
		});
	}

	state = subBytes(state);
	state = shiftRows(state);
	state = addRoundKey(state, roundKeys[10]);
	rounds.push({
		step: 10,
		keyIndex: 10,
		label: "Round 10 (Final)",
		state: state.slice(),
		roundKey: roundKeys[10].slice(),
	});

	return rounds;
};

const decryptBlock = (block: number[], roundKeys: number[][]): AesRound[] => {
	const rounds: AesRound[] = [];
	let state = addRoundKey(block, roundKeys[10]);
	rounds.push({
		step: 0,
		keyIndex: 10,
		label: "Round 0 (AddRoundKey K10)",
		state: state.slice(),
		roundKey: roundKeys[10].slice(),
	});

	let step = 1;
	for (let round = 9; round >= 1; round -= 1) {
		state = invShiftRows(state);
		state = invSubBytes(state);
		state = addRoundKey(state, roundKeys[round]);
		state = invMixColumns(state);
		rounds.push({
			step,
			keyIndex: round,
			label: `Round ${step} (Inv K${round})`,
			state: state.slice(),
			roundKey: roundKeys[round].slice(),
		});
		step += 1;
	}

	state = invShiftRows(state);
	state = invSubBytes(state);
	state = addRoundKey(state, roundKeys[0]);
	rounds.push({
		step,
		keyIndex: 0,
		label: "Round 10 (Final K0)",
		state: state.slice(),
		roundKey: roundKeys[0].slice(),
	});

	return rounds;
};

const runAes = (
	blockHex: string,
	keyHex: string,
	decryptMode: boolean,
): AesResult => {
	const blockParse = parseHex(blockHex, 16);
	if (blockParse.error) {
		return {
			resultHex: "",
			rounds: [],
			roundKeys: [],
			error: blockParse.error,
		};
	}
	const keyParse = parseHex(keyHex, 16);
	if (keyParse.error) {
		return {
			resultHex: "",
			rounds: [],
			roundKeys: [],
			error: keyParse.error,
		};
	}

	const roundKeys = expandKey(keyParse.bytes);
	const rounds = decryptMode
		? decryptBlock(blockParse.bytes, roundKeys)
		: encryptBlock(blockParse.bytes, roundKeys);
	const finalState = rounds[rounds.length - 1]?.state ?? blockParse.bytes;

	return {
		resultHex: bytesToHex(finalState),
		rounds,
		roundKeys,
	};
};

export const encrypt = (blockHex: string, keyHex: string): AesResult =>
	runAes(blockHex, keyHex, false);

export const decrypt = (blockHex: string, keyHex: string): AesResult =>
	runAes(blockHex, keyHex, true);
